// The office's knowledge folder (docs/office.md § Office folder): outside every
// repo (the same rule as shared spaces — `folder-guard.ts`), reused from the
// workspace's shared space when its repos share one, and scaffolded with the
// files the roles read. Scaffolding never overwrites a file a human (or a
// shift) may have edited; only README.md is regenerated, and only while it
// still carries the marker line.
import fs from 'node:fs';
import path from 'node:path';
import { OFFICE_ROLE_KEY_RE, type Office, type OfficeRole, type Repo, type Space, type Workspace } from '@tm/shared';
import { isInside, realPathDeep, validateDedicatedFolder } from '../folder-guard.ts';
import { denyRuleRefusal, untrustedPath } from './isolation.ts';

/** Subdirectory of a shared space folder that holds the office. */
export const OFFICE_SPACE_SUBDIR = 'office';

/** First line of the generated README; a README without it belongs to the human. */
export const OFFICE_README_MARKER = '<!-- tm:office-folder — generated by the Task Manager';

/**
 * Refuse a path inside or containing any registered repo (and `/`, home,
 * relative paths), and one a trusted shift's deny rule could not name exactly
 * (docs/office.md § Isolation — `trustedShiftDenies` would refuse to spawn).
 */
export function validateOfficeFolder(
  raw: string,
  repos: readonly Pick<Repo, 'name' | 'path'>[],
): { path: string } | { error: string } {
  const v = validateDedicatedFolder(raw, repos);
  if ('error' in v) return v;
  const refusal = denyRuleRefusal(v.path) ?? denyRuleRefusal(realPathDeep(v.path));
  return refusal ? { error: refusal } : v;
}

/** The untrusted storage relative to the office folder, as the scaffold writes it (§ Isolation). */
function untrustedRel(office: Pick<Office, 'folderPath'>): string {
  return path.relative(path.resolve(office.folderPath), untrustedPath(office, ''));
}

/**
 * The folder an office of this workspace gets by default: when EVERY repo of
 * the workspace is a member of the same shared space, that space's folder +
 * `office/` (so the office's notes sit beside the space's knowledge); otherwise
 * null and the human picks one. The result is validated like any other path.
 */
export function defaultOfficeFolder(
  workspace: Pick<Workspace, 'repoIds'>,
  spaces: readonly Pick<Space, 'path' | 'repoIds'>[],
  repos: readonly Pick<Repo, 'id' | 'name' | 'path'>[],
): { path: string; source: 'space' } | { error: string } | null {
  const ids = workspace.repoIds.filter((id) => repos.some((r) => r.id === id));
  if (ids.length === 0) return null;
  const space = spaces.find((s) => ids.every((id) => s.repoIds.includes(id)));
  if (!space) return null;
  const v = validateOfficeFolder(path.join(space.path, OFFICE_SPACE_SUBDIR), repos);
  return 'error' in v ? v : { path: v.path, source: 'space' };
}

export interface ScaffoldResult {
  /** paths (relative to the folder) created by this call */
  created: string[];
  /** paths that already existed and were left alone */
  kept: string[];
  /** README.md rewritten (it still carried the marker) */
  readmeUpdated: boolean;
}

type ScaffoldRole = Pick<OfficeRole, 'key' | 'name' | 'title' | 'prompt'>;

const FILES: readonly [rel: string, body: string][] = [
  [
    'vision.md',
    `# Vision\n\nWhat this product is for, who it serves, and what "good" looks like. Every role reads this first.\n\n<!-- Write it in your own words; the office never overwrites this file. -->\n`,
  ],
  [
    'priorities.md',
    `# Priorities\n\nThe ordered list of what matters now. The Director proposes changes; a human decides.\n\n1. \n`,
  ],
  ['roadmap.md', `# Roadmap\n\nWhat comes next, roughly in order, and what is deliberately out of scope.\n\n## Now\n\n## Next\n\n## Later\n`],
];

const DIRS = ['roles', 'briefings', 'deliverables'] as const;

const untrustedReadme = (rel: string) => `# ${rel}/

Text that came from OUTSIDE this server lands here: web pages, outside signals,
pasted reports, command output a shift asked for.

**Agents never read this folder unreviewed.** A shift that reads a file from
here is tainted (docs/office.md § The taint model): it files drafts only, and
later trusted shifts see a digest of it, never its text. Move a file out of
this folder only after a human has read it.
`;

function roleFile(r: ScaffoldRole): string {
  return `# ${r.name} — ${r.title}\n\nRole key: \`${r.key}\`\n\n## Standing instructions\n\n${r.prompt.trim()}\n\n## Notes\n\n<!-- The role's working notes; shifts append here. -->\n`;
}

function readme(office: Pick<Office, 'id'>, roles: readonly ScaffoldRole[], untrusted: string): string {
  const list = roles.map((r) => `- \`roles/${r.key}.md\` — ${r.name}, ${r.title}`).join('\n') || '- (no roles yet)';
  return `${OFFICE_README_MARKER} (docs/office.md § Office folder). Rewritten when the office changes; delete this line to take the file over. -->
# Office folder

Office \`${office.id}\`. Its standing roles read and write here; nothing in this
folder is committed to any repo.

| Path | What it holds |
|---|---|
| \`vision.md\` | what the product is for — human-written |
| \`priorities.md\` | what matters now, in order — human-decided |
| \`roadmap.md\` | what comes next |
| \`roles/<key>.md\` | each role's standing instructions and working notes |
| \`briefings/\` | stand-up and shift briefs |
| \`deliverables/\` | reports and documents the roles produce |
| \`${untrusted}/\` | outside text; agents never read it unreviewed |

## Roles

${list}
`;
}

/** Create `rel` with `body` only when nothing (not even a dangling symlink) is there. */
function createOnce(root: string, rel: string, body: string, res: ScaffoldResult): void {
  try {
    fs.writeFileSync(path.join(root, rel), body, { flag: 'wx' });
    res.created.push(rel);
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== 'EEXIST') throw e;
    res.kept.push(rel);
  }
}

function ensureDir(root: string, rel: string, res: ScaffoldResult): void {
  const p = path.join(root, rel);
  const st = fs.lstatSync(p, { throwIfNoEntry: false });
  if (st) {
    if (!st.isDirectory()) throw new Error(`office folder: ${rel} exists and is not a directory`);
    res.kept.push(`${rel}/`);
    return;
  }
  fs.mkdirSync(p);
  res.created.push(`${rel}/`);
}

/**
 * Create the office folder's skeleton. Idempotent: an existing file is never
 * overwritten (vision/priorities/roadmap/role files are the humans' and the
 * roles' own), a missing one is created, and README.md is regenerated only
 * while its first line is the marker. Pass `repos` to re-check the folder
 * against them first (a refusal throws, nothing is written).
 */
export function scaffoldOfficeFolder(
  office: Pick<Office, 'id' | 'folderPath'>,
  roles: readonly ScaffoldRole[],
  opts: { repos?: readonly Pick<Repo, 'name' | 'path'>[] } = {},
): ScaffoldResult {
  if (opts.repos) {
    const v = validateOfficeFolder(office.folderPath, opts.repos);
    if ('error' in v) throw new Error(`office folder: ${v.error}`);
  }
  if (!path.isAbsolute(office.folderPath)) throw new Error('office folder: path must be absolute');
  for (const r of roles) {
    if (!OFFICE_ROLE_KEY_RE.test(r.key)) throw new Error(`office folder: bad role key "${r.key}"`);
  }
  const root = path.resolve(office.folderPath);
  fs.mkdirSync(root, { recursive: true });
  const realRoot = realPathDeep(root);

  const untrusted = untrustedRel(office);
  const dirs = [...DIRS, untrusted];
  const res: ScaffoldResult = { created: [], kept: [], readmeUpdated: false };
  for (const d of dirs) ensureDir(root, d, res);
  // A subdirectory symlinked out of the folder would let the scaffold write elsewhere.
  for (const d of dirs) {
    if (!isInside(realPathDeep(path.join(root, d)), realRoot)) throw new Error(`office folder: ${d}/ points outside the folder`);
  }
  for (const [rel, body] of FILES) createOnce(root, rel, body, res);
  createOnce(root, path.join(untrusted, 'README.md'), untrustedReadme(untrusted), res);
  for (const r of roles) createOnce(root, `roles/${r.key}.md`, roleFile(r), res);

  const readmePath = path.join(root, 'README.md');
  const next = readme(office, roles, untrusted);
  const st = fs.lstatSync(readmePath, { throwIfNoEntry: false });
  if (!st) {
    createOnce(root, 'README.md', next, res);
  } else if (st.isFile() && fs.readFileSync(readmePath, 'utf8').startsWith(OFFICE_README_MARKER)) {
    if (fs.readFileSync(readmePath, 'utf8') !== next) {
      fs.writeFileSync(readmePath, next);
      res.readmeUpdated = true;
    }
    res.kept.push('README.md');
  } else {
    res.kept.push('README.md');
  }
  return res;
}

/**
 * Reset one role's notes file to its fresh skeleton (docs/office.md § API →
 * reset-notes): the role's standing instructions and an empty Notes section.
 * Written to a temp file and renamed over the old one, so a symlink at
 * `roles/<key>.md` is replaced, never followed; `roles/` itself must resolve
 * inside the folder. Returns the path relative to the folder.
 */
export function resetRoleNotes(office: Pick<Office, 'folderPath'>, role: ScaffoldRole): string {
  if (!OFFICE_ROLE_KEY_RE.test(role.key)) throw new Error(`office folder: bad role key "${role.key}"`);
  if (!path.isAbsolute(office.folderPath)) throw new Error('office folder: path must be absolute');
  const root = path.resolve(office.folderPath);
  const dir = path.join(root, 'roles');
  fs.mkdirSync(dir, { recursive: true });
  if (!isInside(realPathDeep(dir), realPathDeep(root))) throw new Error('office folder: roles/ points outside the folder');
  const rel = `roles/${role.key}.md`;
  const tmp = path.join(dir, `.${role.key}.md.${process.pid}.${Date.now()}.tmp`);
  fs.writeFileSync(tmp, roleFile(role), { flag: 'wx' });
  try {
    fs.renameSync(tmp, path.join(root, rel));
  } catch (e) {
    fs.rmSync(tmp, { force: true });
    throw e;
  }
  return rel;
}

/** Where `archiveRoleNotes` moves notes it finds already present, inside the untrusted storage (agents never read it unreviewed). */
const ARCHIVED_NOTES_SUBDIR = 'archived-notes';

/**
 * Move a `roles/<key>.md` that already exists out of the role's way, into
 * `untrusted/archived-notes/<key>-<stamp>.md` (docs/office.md § API → Notes
 * of a new role). Called before a role is created, and for every role when an
 * office takes a folder, so text left by a deleted role — possibly written by
 * a tainted shift — or by anyone else never becomes a new role's TRUSTED
 * notes. A symlink is moved as the link itself, never followed. Returns the
 * archive path relative to the folder, or null when nothing was there.
 */
export function archiveRoleNotes(office: Pick<Office, 'folderPath'>, key: string): string | null {
  if (!OFFICE_ROLE_KEY_RE.test(key)) throw new Error(`office folder: bad role key "${key}"`);
  if (!path.isAbsolute(office.folderPath)) throw new Error('office folder: path must be absolute');
  const root = path.resolve(office.folderPath);
  const src = path.join(root, 'roles', `${key}.md`);
  if (!fs.lstatSync(src, { throwIfNoEntry: false })) return null;
  if (!isInside(realPathDeep(path.join(root, 'roles')), realPathDeep(root))) throw new Error('office folder: roles/ points outside the folder');
  const dir = untrustedPath(office, ARCHIVED_NOTES_SUBDIR);
  const dirRel = path.relative(root, dir);
  fs.mkdirSync(dir, { recursive: true });
  if (!isInside(realPathDeep(dir), realPathDeep(root))) throw new Error(`office folder: ${dirRel}/ points outside the folder`);
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  let rel = `${dirRel}/${key}-${stamp}.md`;
  for (let i = 2; fs.lstatSync(path.join(root, rel), { throwIfNoEntry: false }); i++) rel = `${dirRel}/${key}-${stamp}-${i}.md`;
  fs.renameSync(src, path.join(root, rel));
  return rel;
}
